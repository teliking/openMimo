"""Extract SDK/wire resolution pairs identified in the native initializer.

The initializer at 0x14fb38c copies 0x138 bytes from 0xbdbe9c and inserts
successive eight-byte pairs into SDKCameraUtility::resolution_sdk_protocol_map_.
The recovered ELF is an analysis copy; the source APK remains unchanged.
"""
import hashlib
import json
import struct
from capstone import Cs, CS_ARCH_ARM64, CS_MODE_ARM
from capstone.arm64_const import ARM64_OP_IMM, ARM64_REG_X1, ARM64_REG_X8, ARM64_REG_X19, ARM64_REG_SP
from pathlib import Path
from elftools.elf.elffile import ELFFile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'analysis/libdjisdk_jni-static-restored.so'
TABLE_ADDRESS = 0xbdbe9c
TABLE_SIZE = 0x138
with SOURCE.open('rb') as stream:
    elf = ELFFile(stream)
    def read_at(address, size):
        segment = next(s for s in elf.iter_segments() if s.header.p_type == 'PT_LOAD'
                       and s.header.p_vaddr <= address
                       and address + size <= s.header.p_vaddr + s.header.p_filesz)
        stream.seek(segment.header.p_offset + address - segment.header.p_vaddr)
        return stream.read(size)
    raw = read_at(TABLE_ADDRESS, TABLE_SIZE)
    frame_raw = read_at(0xbdc054, 24 * 4)
    initializer_raw = read_at(0x14fb38c, 0xa2c)
assert len(raw) == TABLE_SIZE
pairs = [{'sdk': sdk, 'wire': wire} for sdk, wire in struct.iter_unpack('<II', raw)]
assert all(p['wire'] <= 255 for p in pairs)
disassembler = Cs(CS_ARCH_ARM64, CS_MODE_ARM)
disassembler.detail = True
stack_offsets, insertions = {ARM64_REG_SP: 0}, []
for insn in disassembler.disasm(initializer_raw, 0x14fb38c):
    ops = insn.operands
    if insn.mnemonic == 'mov' and len(ops) == 2 and ops[0].reg in (ARM64_REG_X1, ARM64_REG_X8, ARM64_REG_X19):
        value = stack_offsets.get(ops[1].reg)
        stack_offsets.pop(ops[0].reg, None)
        if value is not None:
            stack_offsets[ops[0].reg] = value
    elif insn.mnemonic == 'add' and len(ops) == 3 and ops[0].reg in (ARM64_REG_X1, ARM64_REG_X8, ARM64_REG_X19) and ops[2].type == ARM64_OP_IMM:
        value = stack_offsets.get(ops[1].reg)
        stack_offsets.pop(ops[0].reg, None)
        if value is not None:
            stack_offsets[ops[0].reg] = value + ops[2].imm
    elif insn.mnemonic == 'bl' and ops[0].imm == 0x263cce0:
        insertions.append({'address': hex(insn.address), 'table_offset': stack_offsets.get(ARM64_REG_X1)})
assert [i['table_offset'] for i in insertions] == list(range(0, TABLE_SIZE, 8)), insertions
output = {'source_apk_sha256': '877cce18fb21cbdb6e025965e7eab4b06d823675428f61b14f641b719454c2a2',
          'initializer': '0x14fb38c', 'table_address': hex(TABLE_ADDRESS),
          'table_sha256': hashlib.sha256(raw).hexdigest(),
          'fallback': 'identity; SDK-to-wire narrows to one byte at caller',
          'pairs': pairs,
          'verified_native_insertions': insertions,
          'frame_rate_from_wire_address': '0x14f9484',
          'frame_rate_table_address': '0xbdc054',
          'frame_rate_table_mask': '0x9fffff',
          'frame_rate_protocol_to_sdk': list(struct.unpack('<24I', frame_raw))}
destination = ROOT / 'protocol/pocket3/resolution-map.json'
destination.write_text(json.dumps(output, indent=2) + '\n', encoding='utf-8')
generated = ['// Code generated by scripts/extract_resolution_mapping.py; DO NOT EDIT.',
             '// Source: Mimo 2.12.1 native SDKCameraUtility initializer.',
             'package pocket3', '',
             'var nativeResolutionPairs = [...]struct { sdk uint32; wire byte }{']
generated += [f'{{{p["sdk"]}, {p["wire"]}}},' for p in pairs]
generated += ['}', '', 'var nativeFrameRateFromWire = [...]uint32{',
              ','.join(map(str, output['frame_rate_protocol_to_sdk'])) + ',', '}', '']
(destination.parent / 'conversion_generated.go').write_text('\n'.join(generated), encoding='utf-8')
print('Extracted', len(pairs), 'resolution pairs and 24 frame-rate entries')
print('Non-identity resolution pairs:', [p for p in pairs if p['sdk'] != p['wire']])
print('Frame-rate table:', output['frame_rate_protocol_to_sdk'])
